// Static build for the HackOnVibe team subdomain (their CI runs `npm run build` on Node 20
// and publishes ./dist). The page talks to the Tapsplit API deployed on Cloudflare Workers,
// whose URL comes from deploy.config.json (written by `npm run cf:deploy`) or TAPSPLIT_API.
import { cpSync, existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';

const OUT = 'dist';
const cfg = existsSync('deploy.config.json') ? JSON.parse(readFileSync('deploy.config.json', 'utf8')) : {};
const api = String(process.env.TAPSPLIT_API || cfg.api || '').replace(/\/+$/, '');

rmSync(OUT, { recursive: true, force: true });
cpSync('public', OUT, { recursive: true });
writeFileSync(
  `${OUT}/config.js`,
  `// Generated by scripts/build.mjs\nwindow.TAPSPLIT_CONFIG = ${JSON.stringify({ api, shareBase: api })};\n`,
);

console.log(`Built ${OUT}/ (API: ${api || 'same origin'})`);
if (!api) console.warn('No API URL set: run `npm run cf:deploy` (or set TAPSPLIT_API) so the static site can reach the backend.');
